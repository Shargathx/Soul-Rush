// Builds docs/playtest-form.gs from tools/docs/questionnaire.js: a Google Apps Script that creates the playtest Google Form (and a
// spreadsheet that collects the answers) in one run. Run: node tools/docs/form_script.js
// build() is also used by a test, which checks that the checked-in .gs matches the data.
const fs = require("fs"), path = require("path");
const q = require("./questionnaire.js");
const J = JSON.stringify;

function build() {
  const out = [];
  out.push("// Soul Rush playtest form. GENERATED by tools/docs/form_script.js from tools/docs/questionnaire.js: edit the data, not this file.");
  out.push("//");
  out.push("// How to use: go to script.google.com, click New project, delete the sample code, paste this whole file, click Run on createPlaytestForm");
  out.push("// and accept the permissions (it needs Forms and Sheets: it creates a form in your Drive and a spreadsheet for the answers).");
  out.push("// Then open View > Logs (or Execution log) to see the form's edit link and the link to send to testers.");
  out.push("");
  out.push("function createPlaytestForm() {");
  out.push("  var form = FormApp.create(" + J(q.title) + ");");
  out.push("  form.setDescription(" + J(q.description) + ");");
  out.push("  form.setConfirmationMessage(" + J(q.confirmation) + ");");
  out.push("  form.setProgressBar(true);");
  out.push("  form.setCollectEmail(false);");
  out.push("  var item;");
  q.sections.forEach((s, si) => {
    out.push("");
    if (si > 0) out.push("  form.addPageBreakItem().setTitle(" + J(s.title) + ")" + (s.help ? ".setHelpText(" + J(s.help) + ")" : "") + ";");
    else out.push("  form.addSectionHeaderItem().setTitle(" + J(s.title) + ");");
    if (si === 0 && s.help) out.push("  // " + s.help);
    for (const x of s.questions) {
      switch (x.kind) {
        case "scale":
          out.push("  form.addScaleItem().setTitle(" + J(x.text) + ").setBounds(1, 5).setLabels(" + J(x.low) + ", " + J(x.high) + ");"); break;
        case "choice":
          out.push("  item = form.addMultipleChoiceItem().setTitle(" + J(x.text) + ");");
          out.push("  item.setChoices([" + x.options.map(o => "item.createChoice(" + J(o) + ")").join(", ") + "]);");
          if (x.other) out.push("  item.showOtherOption(true);");
          break;
        case "multi":
          out.push("  item = form.addCheckboxItem().setTitle(" + J(x.text) + ");");
          out.push("  item.setChoices([" + x.options.map(o => "item.createChoice(" + J(o) + ")").join(", ") + "]);");
          if (x.other) out.push("  item.showOtherOption(true);");
          break;
        case "short": out.push("  form.addTextItem().setTitle(" + J(x.text) + ");"); break;
        case "long": out.push("  form.addParagraphTextItem().setTitle(" + J(x.text) + ");"); break;
        case "grid":
          out.push("  form.addGridItem().setTitle(" + J(x.text) + ").setHelpText(" + J("1 = " + x.low.toLowerCase() + ", 5 = " + x.high.toLowerCase()) + ").setRows(" + J(x.rows) + ").setColumns(" + J(["1", "2", "3", "4", "5"]) + ");"); break;
        default: throw new Error("unknown question kind " + x.kind);
      }
    }
  });
  out.push("");
  out.push("  var sheet = SpreadsheetApp.create(" + J(q.title + " (answers)") + ");");
  out.push("  form.setDestination(FormApp.DestinationType.SPREADSHEET, sheet.getId());");
  out.push("");
  out.push("  Logger.log('Edit the form here: ' + form.getEditUrl());");
  out.push("  Logger.log('Send testers this link: ' + form.getPublishedUrl());");
  out.push("  Logger.log('Answers collect in: ' + sheet.getUrl());");
  out.push("}");
  return out.join("\n") + "\n";
}

module.exports = { build };
if (require.main === module) {
  const dst = path.join(__dirname, "..", "..", "docs", "playtest-form.gs");
  fs.writeFileSync(dst, build());
  const n = q.sections.reduce((t, s) => t + s.questions.length, 0);
  console.log("wrote", dst, "(" + n + " questions in " + q.sections.length + " sections)");
}
