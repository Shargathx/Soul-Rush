// Project integrity: the files GDevelop needs are there, registered, and readable.
const fs = require("fs");
const path = require("path");
const { ROOT, load, walk, codeOf, exists } = require("./lib");

module.exports = [
  ["every registered resource file exists", () => {
    const { project } = load();
    return project.resources.resources.filter(r => r.file && !exists(r.file)).map(r => r.kind + " " + r.file + " (resource " + r.name + ")");
  }],

  ["every sprite frame and texture is a registered resource", () => {
    const { project, scenes } = load();
    const names = new Set(project.resources.resources.map(r => r.name));
    const bad = [];
    const check = (o, where) => {
      for (const a of o.animations || []) for (const d of a.directions || []) for (const s of d.sprites || []) if (!names.has(s.image)) bad.push(where + ": " + o.name + " frame " + s.image);
      if (o.texture && !names.has(o.texture)) bad.push(where + ": " + o.name + " texture " + o.texture);
    };
    for (const o of project.objects) check(o, "global");
    for (const s of scenes) for (const o of s.objects || []) check(o, s.name);
    // A known, harmless leftover: the invisible wall's placeholder frame (it is never drawn).
    return bad.filter(b => !/Invisible_Wall frame NewSprite20\.png/.test(b));
  }],

  ["every sound or music file the events use exists and is registered", () => {
    const { project, scenes, sheets } = load();
    const reg = new Set(project.resources.resources.map(r => r.file));
    const re = /assets\/(?:Sfx|Music)\/[^"\\]+?\.(?:wav|mp3|ogg)/g, used = new Set();
    for (const f of scenes.map(s => s.file).concat(sheets.map(s => s.file))) for (const m of fs.readFileSync(path.join(ROOT, f), "utf8").matchAll(re)) used.add(m[0]);
    return [...used].flatMap(f => !exists(f) ? ["missing file " + f] : !reg.has(f) ? ["not registered " + f] : []);
  }],

  ["every link points at an event sheet that exists", () => {
    const { scenes, sheets } = load();
    const names = new Set(sheets.map(s => s.name)), bad = [];
    for (const x of scenes.concat(sheets)) walk(x.events, e => { if (e.type === "BuiltinCommonInstructions::Link" && !names.has(e.target)) bad.push(x.file + " links missing sheet " + e.target); });
    return bad;
  }],

  ["every event sheet belongs to a scene that exists", () => {
    const { scenes, sheets } = load();
    const names = new Set(scenes.map(s => s.name));
    return sheets.filter(s => !names.has(s.associatedLayout)).map(s => s.file + " is associated with missing scene " + s.associatedLayout);
  }],

  ["every JavaScript event parses", () => {
    const { scenes, sheets } = load(), bad = [];
    for (const x of scenes.concat(sheets)) walk(x.events, e => {
      if (e.type !== "BuiltinCommonInstructions::JsCode") return;
      try { new Function("runtimeScene", "objects", "eventsFunctionContext", "gdjs", codeOf(e)); }
      catch (err) { bad.push(x.file + ": " + err.message + " in: " + codeOf(e).split("\n")[0].slice(0, 80)); }
    });
    return bad;
  }],

  ["the hub's generated script events are present (tools/hub/build.js)", () => {
    // The hub's gates, crows, dialog, sounds and music are script events written by tools/hub/build.js. If a GDevelop
    // save or a hand edit dropped them, the hub would load but do nothing.
    const hub = load().scenes.find(s => s.name === "HUB_Area");
    if (!hub) return ["HUB_Area scene not found"];
    const gen = [];
    walk(hub.events, e => { if (e.type === "BuiltinCommonInstructions::JsCode" && /Generated by tools\/hub\/build\.js/.test(codeOf(e))) gen.push(e); });
    return gen.length >= 5 ? [] : ["expected the hub's generated script events (found " + gen.length + ")"];
  }]
];
