// Builds the Cat and Bladekeeper fights: cuts their frames, makes their objects, a scene (from an arena template) and an event
// sheet that runs the boss script (kit.js + cat.js / bladekeeper.js), registers everything in the project and adds the bosses
// to the fight UI's name table. Safe to run again: it rebuilds its own scene and sheet from scratch.
// Close GDevelop first. Usage: node tools/bosses/build.js [cat] [bladekeeper]
const fs = require("fs");
const path = require("path");
const L = require("./lib.js");

const NAMES = ["cat", "bladekeeper"];
const wanted = process.argv.slice(2).filter(a => NAMES.includes(a));
const ids = wanted.length ? wanted : NAMES.filter(n => fs.existsSync(path.join(__dirname, n + ".def.js")));
const SPECS = {}; for (const n of ids) SPECS[n] = require("./" + n + ".def.js");
const src = f => fs.readFileSync(path.join(__dirname, f), "utf8").replace(/\r\n/g, "\n");

const project = L.readJson("Soul Rush.json");

// The code of a boss's script event: its config, the kit, the boss script, and the call that runs it each frame.
function bossCode(spec, anims, sfx) {
  const cfg = { boss: spec.object, hitbox: spec.object + "_Hitbox", projectile: spec.projectile || null, ground: spec.ground, minX: spec.minX, maxX: spec.maxX,
    zones: !!spec.zones, sfx, fx: spec.fx || {}, points: spec.points || {}, scale: spec.scale, cell: spec.cell, anims: {} };
  for (const a of anims) cfg.anims[a.name] = { n: a.frames.length, dt: a.dt, loop: a.loop };
  return [
    "// " + spec.name + ": generated by tools/bosses/build.js from tools/bosses/kit.js and tools/bosses/" + spec.ai + ". Edit those and rebuild.",
    "// " + spec.summary,
    "const CFG = " + JSON.stringify(cfg) + ";",
    src("kit.js"), src(spec.ai),
    "const kit = runtimeScene.__bossKit || (runtimeScene.__bossKit = makeKit(runtimeScene, CFG, " + spec.aiFn + "));",
    "kit.step();",
    "// Debug keys (the DEBUG_KEYS switch in Combat_Shared turns them off with the rest): each starts one of the moves at once; Numpad0 takes a life (HP to 0).",
    "const KEYS = " + JSON.stringify(spec.debugKeys || {}) + ";",
    "const input = gdjs.evtTools && gdjs.evtTools.input;",
    "if (input) for (const key in KEYS) if (input.wasKeyJustPressed(runtimeScene, key)) { if (KEYS[key] === \"loseLife\") kit.set(\"Health\", 0); else if (KEYS[key] === \"toggleIdle\") kit.toggleDebugIdle(); else kit.force(KEYS[key]); }"
  ].join("\n");
}

function audio(file, music) {
  return { file, kind: "audio", metadata: "", name: file, preloadAsMusic: false, preloadAsSound: false, preloadInCache: false, userAdded: false };
}

for (const id of ids) {
  const spec = SPECS[id];
  const anims = spec.cut();
  const sfx = {};
  for (const k of Object.keys(spec.sfx || {})) sfx[k] = spec.sfx[k].filter(f => fs.existsSync(path.join(L.ROOT, f)));
  const files = anims.flatMap(a => a.frames.map(f => f.image));

  // The objects.
  const [w, h] = [spec.cell * spec.scale, spec.cellH ? spec.cellH * spec.scale : spec.cell * spec.scale];
  const boss = L.spriteObject(spec.object, spec.vars, anims.map(a => L.animation(a.name, a.frames, a.dt, a.loop)));
  const extras = spec.extras(anims), objects = [boss].concat(extras.map(e => e[0]));
  for (const o of objects) for (const a of o.animations) for (const d of a.directions) for (const s of d.sprites) files.push(s.image);
  L.registerImages(project, [...new Set(files)]);
  for (const f of sfx.meow || []) if (!project.resources.resources.some(r => r.name === f)) project.resources.resources.push(audio(f));
  for (const f of Object.values(sfx).flat()) if (!project.resources.resources.some(r => r.name === f)) project.resources.resources.push(audio(f));
  if (spec.music && !project.resources.resources.some(r => r.name === spec.music.file)) project.resources.resources.push(audio(spec.music.file, true));

  // The scene: the arena template, plus the boss, its groups, music and the link to its sheet.
  const tpl = L.readJson("layouts/" + spec.template + ".json");
  const scene = JSON.parse(JSON.stringify(tpl));
  scene.name = spec.scene; scene.mangledName = spec.scene.replace(/_/g, "_95"); scene.title = "";
  scene.objects = scene.objects.filter(o => !objects.some(x => x.name === o.name)).concat(objects);
  scene.instances = scene.instances.filter(i => !objects.some(x => x.name === i.name));
  scene.instances.push(L.instance(spec.object, spec.start[0], spec.start[1], w, h, 16));
  const group = (name, members) => { const g = scene.objectsGroups.find(x => x.name === name); g.objects = g.objects.filter(o => !objects.some(x => x.name === o.name && members.includes(x.name))); for (const m of members) g.objects.push({ name: m }); };
  group("Enemy", [spec.object]);
  group("EnemyHitbox", extras.filter(e => e[1] === "EnemyHitbox").map(e => e[0].name));
  L.addToFolder(scene.objectsFolderStructure, spec.folder, objects.map(o => o.name));
  const t = tpl.events; // Template: comment, Link PM, comment, Link CS, comment, hide walls, comment, arena script.
  const music = L.standard([L.cond("SceneJustBegins", [""])], [L.act("PlayMusic", ["", spec.music.file, "yes", String(spec.music.volume), ""])]);
  scene.events = [
    L.comment(spec.name + ": the fight scene, made by tools/bosses/build.js from " + spec.template + ". The boss is the " + spec.object + " object (Enemy group); everything that hurts the player is in the EnemyHitbox group."),
    t[1], t[2], t[3],
    L.comment("Scene start: play this scene's own music."), music,
    t[4], t[5], t[6], t[7],
    L.comment(spec.name + ": his script (kit and moves), from the " + spec.sheet + " sheet."),
    L.link(spec.sheet)
  ];
  L.writeJson("layouts/" + spec.scene.toLowerCase() + ".json", scene);

  // The sheet.
  L.writeJson("externalEvents/" + spec.sheet.toLowerCase() + ".json", { associatedLayout: spec.scene, name: spec.sheet, events: [
    L.comment(spec.sheet + ": the " + spec.name + " fight. " + spec.summary + " The scene links Player_Movement and Combat_Shared before this sheet. All of it is one script (a state machine of moves written as generators, see tools/bosses/kit.js); the numbers are variables on the " + spec.object + " object."),
    L.jsEvent(bossCode(spec, anims, sfx))
  ] });
  L.registerSplit(project, "layouts", "/layouts/" + spec.scene.toLowerCase());
  L.registerSplit(project, "externalEvents", "/externalEvents/" + spec.sheet.toLowerCase());
  L.registerListed(project, "layoutsFolderStructure", spec.scene); L.registerListed(project, "externalEventsFolderStructure", spec.sheet);

  // The fight UI's table: which object is the boss in this scene, and the name shown over its bars.
  const cs = L.readJson("externalEvents/combat_shared.json");
  (function visit(list) { for (const e of list) {
    if (e.type === "BuiltinCommonInstructions::JsCode" && Array.isArray(e.inlineCode) && e.inlineCode.some(l => /const BOSSES = \{/.test(l))) {
      e.inlineCode = e.inlineCode.filter(l => !l.startsWith("    " + spec.scene + ":"));
      const at = e.inlineCode.findIndex(l => /const BOSSES = \{/.test(l)), end = e.inlineCode.findIndex((l, i) => i > at && /^  \};/.test(l));
      e.inlineCode[end - 1] = e.inlineCode[end - 1].replace(/,?$/, ",");
      e.inlineCode.splice(end, 0, "    " + spec.scene + ": { obj: \"" + spec.object + "\", name: \"" + spec.name + "\" }");
      return true;
    }
    if (e.events && visit(e.events)) return true;
  } })(cs.events);
  L.writeJson("externalEvents/combat_shared.json", cs);
  console.log(spec.scene + ": " + anims.length + " animations, " + anims.reduce((n, a) => n + a.frames.length, 0) + " frames, " + objects.length + " objects");
}
L.writeJson("Soul Rush.json", project);
